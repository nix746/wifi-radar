function fig = gen_fig_4_7_stat_outdoor(show_figure, save_png, force_recompute)
% GEN_FIG_4_7_STAT_OUTDOOR
% Experiment SIM-6b (Monte Carlo, Outdoor): detection probability vs. range
% for Binary STC and Coherent STC in a random outdoor scene.
% Figure 4.7 for Chapter 4 of the thesis:
%   IEEE 802.11ax CBW40, MCS 4, TGax Model-E (large open space), R in [5, 105] m,
%   per trial: 0-2 cars, 2-3 slow pedestrians, 1-2 cyclists, 1-2 animals,
%   fresh scene, channel realization and AWGN in every trial.
%   SNR = 28 dB: constant AP power, half the bandwidth -> 3 dB lower thermal noise
%   than the 80 MHz indoor scenario (same physics as Exp. E1).
%
% Results are cached in results/exp6_mc_outdoor.mat (recomputed when the
% scenario config changes or force_recompute is true).
%
% Output file: thesis/img/ch4_sim/rys_4_7_statystyka_outdoor.png

    if nargin < 1 || isempty(show_figure),     show_figure     = true;  end
    if nargin < 2 || isempty(save_png),        save_png        = true;  end
    if nargin < 3 || isempty(force_recompute), force_recompute = false; end

    project_root = fullfile(fileparts(mfilename('fullpath')), '..', '..', '..');
    addpath(project_root);
    project_root = init_paths();

    fprintf('=================================================================\n');
    fprintf('  Generating Fig. 4.7: Outdoor Monte Carlo P_D(R) (Exp. SIM-6b)\n');
    fprintf('=================================================================\n');

    cfg = struct( ...
        'name',          'Outdoor', ...
        'standard',      '802.11ax', ...
        'cbw',           'CBW40', ...
        'mcs',           4, ...
        'channel_model', 'Model-E', ...
        'snr_dB',        28.0, ...
        'p_FA',          1e-3, ...
        'n_trials',      60, ...
        'seed',          2027, ...
        'range_lim',     [5, 105], ...
        'range_edges',   5:10:105, ...
        'gate_v_factor', 1.25);

    cfg.classes = [ ...
        struct('key', 'car',        'type', 'car',   'rcs', 10.0, 'count_set', [0, 1, 2], 'vel_abs_lim', [8.0, 22.0]), ...
        struct('key', 'pedestrian', 'type', 'human', 'rcs', 1.0,  'count_set', [2, 3],    'vel_abs_lim', [0.8, 2.2]), ...
        struct('key', 'cyclist',    'type', 'human', 'rcs', 1.0,  'count_set', [1, 2],    'vel_abs_lim', [4.0, 9.0]), ...
        struct('key', 'animal',     'type', 'pet',   'rcs', 0.1,  'count_set', [1, 2],    'vel_abs_lim', [1.5, 7.0]) ...
        ];

    cache_file = fullfile(project_root, 'results', 'exp6_mc_outdoor.mat');
    mc = run_detection_monte_carlo(cfg, cache_file, force_recompute);

    sig = char(963); sq = char(178);
    styles = [ ...
        struct('label', sprintf('Samochód (%s = 10 m%s)', sig, sq),   'color', [0.49, 0.18, 0.56], 'marker', 'd'), ...
        struct('label', sprintf('Pieszy (%s = 1 m%s)', sig, sq),      'color', [0.00, 0.45, 0.74], 'marker', 'o'), ...
        struct('label', sprintf('Rowerzysta (%s = 1 m%s)', sig, sq),  'color', [0.47, 0.67, 0.19], 'marker', '^'), ...
        struct('label', sprintf('Zwierzę (%s = 0,1 m%s)', sig, sq),   'color', [0.85, 0.33, 0.10], 'marker', 's') ...
        ];

    fig = plot_detection_vs_range(mc, styles, ...
        'Skuteczność detekcji w funkcji odległości – scenariusz zewnętrzny (TGax Model-E, 40 MHz)');

    save_thesis_figure(fig, 'ch4_sim', 'rys_4_7_statystyka_outdoor.png', show_figure, save_png);
    if ~show_figure
        fig = [];
    end
    fprintf('=================================================================\n');
end
